// Build options shared by `npm run build`/`dev` and the test suites, so tests
// exercise exactly the module graph that ships.
import builtins from "builtin-modules";
import fs from "node:fs";

export const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, visit the plugin's github repository
*/
`;

export const obsidianExternals = [
	"obsidian",
	"electron",
	"@codemirror/autocomplete",
	"@codemirror/collab",
	"@codemirror/commands",
	"@codemirror/language",
	"@codemirror/lint",
	"@codemirror/search",
	"@codemirror/state",
	"@codemirror/view",
	"@lezer/common",
	"@lezer/highlight",
	"@lezer/lr",
];

const builtinSet = new Set([...builtins, ...builtins.map((name) => `node:${name}`)]);
const STUBBED_BY_BROWSER_FIELD = /^(path|url|fs|source-map-js)$/;
const BROWSER_SAFE_IMPORTERS = /node_modules[\\/](postcss|picocolors|nanoid|postcss-value-parser)[\\/]/;

/**
 * Node built-ins are never loaded at module-evaluation time on mobile.
 *  - PostCSS imports path/url/fs/source-map-js only for optional source-map
 *    features; its package.json "browser" field maps them to empty modules.
 *    Because built-ins are otherwise external, that mapping would be bypassed,
 *    so it is applied explicitly here.
 *  - The desktop HTTP server lazily require()s built-ins inside a function; those
 *    stay external and are never evaluated on mobile.
 */
export const nodeBuiltinPolicy = {
	name: "node-builtin-policy",
	setup(build) {
		build.onResolve({ filter: /.*/ }, (args) => {
			if (args.kind === "entry-point") return null;
			if (STUBBED_BY_BROWSER_FIELD.test(args.path) && BROWSER_SAFE_IMPORTERS.test(args.importer)) {
				return { path: args.path, namespace: "browser-empty" };
			}
			if (builtinSet.has(args.path)) return { path: args.path, external: true };
			return null;
		});
		build.onLoad({ filter: /.*/, namespace: "browser-empty" }, () => ({
			contents: "module.exports = {};",
			loader: "js",
		}));
	},
};

/** esbuild options for the plugin bundle (`main.js`). */
export function pluginBuildOptions({ prod }) {
	return {
		banner: { js: banner },
		entryPoints: ["main.ts"],
		bundle: true,
		platform: "browser",
		loader: { ".css": "text" },
		define: { "process.env.NODE_ENV": '"production"', "process.env.LANG": '""' },
		external: obsidianExternals,
		plugins: [nodeBuiltinPolicy],
		format: "cjs",
		target: "es2018",
		logLevel: "info",
		sourcemap: prod ? false : "inline",
		treeShaking: true,
		outfile: "main.js",
		minify: prod,
	};
}

/** Options for bundling an arbitrary test entry as a browser IIFE. */
export function browserTestBuildOptions(extra) {
	return {
		bundle: true,
		format: "iife",
		platform: "browser",
		loader: { ".css": "text" },
		define: { "process.env.NODE_ENV": '"production"', "process.env.LANG": '""' },
		plugins: [nodeBuiltinPolicy],
		target: "es2020",
		logLevel: "silent",
		...extra,
	};
}

/**
 * Obsidian loads `styles.css` from the plugin root. The adapted Style
 * stylesheet is the single source (also embedded in the preview document).
 */
export function copyStylesheet() {
	fs.copyFileSync("src/vendor/style-html-viewer/styles.css", "styles.css");
}
